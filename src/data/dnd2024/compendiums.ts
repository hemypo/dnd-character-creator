/**
 * Filter spells from 2024 dataset by query, level, and class.
 */
export function searchSpells(
  query: string = '',
  level?: number,
  className?: string
): SpellEntry[] {
  const spells = rawSpells as SpellEntry[];
  const q = query.trim().toLowerCase();
  const cNorm = className ? className.trim().toLowerCase() : '';

  return spells.filter((spell) => {
    // Level filter
    if (level !== undefined && level !== null && spell.level !== level) {
      return false;
    }

    // Class filter
    if (cNorm && !spell.classes.map((c) => c.toLowerCase()).includes(cNorm)) {
      return false;
    }

    // Query filter (name, slug)
    if (q) {
      const matchName = spell.name.toLowerCase().includes(q);
      const matchSlug = spell.slug.toLowerCase().includes(q);
      if (!matchName && !matchSlug) {
        return false;
      }
    }

    return true;
  });
}
